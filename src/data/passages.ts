export function findPassageById(id: string) {
  return passages.find((passage) => passage.id === id) ?? passages[0];
}

export function findPassagesByTheme(theme: ThemeKey) {
  return passages.filter((passage) => passage.themes.includes(theme));
}

export function getPassageForTheme(theme: ThemeKey) {
  return findPassagesByTheme(theme)[0] ?? passages[0];
}
